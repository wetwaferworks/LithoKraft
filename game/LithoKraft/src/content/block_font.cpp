const char* blockFont3x5Labels(char c) {
  if (const char* g = blockFont3x5(c)) return g;
  // Copied verbatim from cBoltLabWorld::glyph (cBoltLabWorld.cpp, letters[]: J, Q, V, Z).
  switch (c) {
    case 'J': return "..#..#..##.####";
    case 'Q': return "####.##.####..#";
    case 'V': return "#.##.##.##.#.#.";
    case 'Z': return "###..#.#.#..###";
    default: return nullptr;
  }
}

