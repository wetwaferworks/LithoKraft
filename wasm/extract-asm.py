#!/usr/bin/env python3
# extract-asm.py <glue.js> <out lkasm.js>
#
# The engine's EM_ASM snippets are its own C++ source text; the toolchain
# extracts them at link time into the generated glue's ASM_CONSTS table,
# keyed by address (they never exist in wasm memory). Our thin layer
# carries that table as data: this script lifts the object literal out of
# OUR OWN build's glue, verbatim, and wraps it in a factory that binds the
# bodies to the loader's environment (lkboot.js supplies the helpers the
# bodies reference: wasmMemory, UTF8ToString, Module, ...). Regenerated
# on every build by build-thin.sh so addresses always match the binary.
import sys

HEADER = """// lkasm.js — the engine's EM_ASM body table for the thin layer.
//
// GENERATED by extract-asm.py from our own build's generated glue; do
// not hand-edit (rebuild instead). The bodies are the engine's own
// EM_ASM source snippets (from window_emscripten.cpp, miniaudio glue,
// lk_webio), extracted by the toolchain at link time and keyed by the
// address the binary passes at runtime. lkboot.js looks bodies up here
// and runs them in its own environment — no generated glue is loaded.
function lkAsmConsts(env) {
  with (env) {
    return """

FOOTER = """;
  }
}
"""

def main():
    src_path, out_path = sys.argv[1], sys.argv[2]
    src = open(src_path, encoding='utf-8').read()
    i = src.find('ASM_CONSTS = {')
    if i < 0:
        sys.exit('ASM_CONSTS table not found in ' + src_path)
    start = src.find('{', i)
    j = src.find('// Imports from the Wasm binary', start)
    if j < 0:
        sys.exit('ASM_CONSTS terminator not found')
    chunk = src[start:j].rstrip()
    if not chunk.endswith('};'):
        sys.exit('unexpected ASM_CONSTS tail: ' + chunk[-40:])
    lit = chunk[:-1].rstrip()
    with open(out_path, 'w', encoding='utf-8') as f:
        f.write(HEADER + lit + FOOTER)
    print('extract-asm: wrote', out_path)

if __name__ == '__main__':
    main()
