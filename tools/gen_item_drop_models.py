#!/usr/bin/env python3
"""Build game/LithoKraft/src/game/item_drop_models.inc from the dropped-item meshes.

Input: game/LithoKraft/assets/models/item_drops/*.json (CloudAtlas low-poly drop meshes,
format lithokraft-item-drop-mesh-v1, 2026-11-17). Output: one flat vertex table plus one row
per model. The game draws these in place of the old flat billboard.

Each vertex carries: position in blocks (model space, 0..1 footprint, y up from the base), UV in
0..255 (v = 0 at the top of the image, the engine's convention), and the face slot whose
texture layer it takes from the item's block (top, bottom, front = north, back = south,
right = east, left = west).

Models are sorted by id, so the output is the same on every run.
Usage: python3 tools/gen_item_drop_models.py [--check]
"""
import glob
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "game", "LithoKraft", "assets", "models", "item_drops")
OUT = os.path.join(ROOT, "game", "LithoKraft", "src", "game", "item_drop_models.inc")
SLOTS = {"top": 0, "bottom": 1, "north": 2, "south": 3, "west": 4, "east": 5}  # FaceSlot order
SHAPES = {"full_block": 0, "half_slab": 1, "component_slab": 2, "special": 3, "foliage": 4}


def fmt(v):
    s = "%.6g" % float(v)
    if "." not in s and "e" not in s:
        s += ".0"
    return s + "f"


def slot_of(material):
    stem = re.sub(r"\.png$", "", material)
    side = stem.rsplit("_", 1)[-1]
    if side not in SLOTS:
        raise SystemExit("unknown face side in material %r" % material)
    return SLOTS[side]


def build():
    files = sorted(glob.glob(os.path.join(SRC, "*.json")))
    files = [f for f in files if os.path.basename(f) != "inventory.json"]
    models = []
    for f in files:
        d = json.load(open(f, encoding="utf-8"))
        if d.get("format") != "lithokraft-item-drop-mesh-v1":
            continue
        models.append(d)
    models.sort(key=lambda d: d["id"])
    verts, rows = [], []
    for d in models:
        first = len(verts)
        pos, uvs = d["positions"], d["uvs"]
        for face in d["faces"]:
            slot = slot_of(face["material"])
            for tri in face["tris"]:
                for i in tri:
                    p, uv = pos[i], uvs[i]
                    u = max(0, min(255, int(round(float(uv[0]) * 255))))
                    v = max(0, min(255, int(round(float(uv[1]) * 255))))
                    verts.append("{%s, %s, %s, %d, %d, %d}" % (fmt(p[0]), fmt(p[1]), fmt(p[2]), u, v, slot))
        bmin, bmax = d["bounds"]["min"], d["bounds"]["max"]
        rows.append('{"%s", %d, %d, %d, {%s, %s, %s}, {%s, %s, %s}}' % (
            d["id"], SHAPES[d["shape_class"]], first, len(verts) - first,
            fmt(bmin[0]), fmt(bmin[1]), fmt(bmin[2]), fmt(bmax[0]), fmt(bmax[1]), fmt(bmax[2])))
    out = ["// Generated by tools/gen_item_drop_models.py from assets/models/item_drops (CloudAtlas,",
           "// 2026-11-17). Do not edit by hand; rerun the script.",
           "// %d models, %d vertices (%d triangles)." % (len(rows), len(verts), len(verts) // 3),
           "// clang-format off",
           "static const ItemDropVertex kItemDropVertices[] = {"]
    out += ["  %s," % v for v in verts]
    out += ["};", "static const ItemDropModelRow kItemDropModelRows[] = {"]
    out += ["  %s," % r for r in rows]
    out += ["};", "// clang-format on", ""]
    return "\r\n".join(out)


def main():
    text = build()
    if "--check" in sys.argv:
        cur = open(OUT, "rb").read().decode("utf-8") if os.path.exists(OUT) else ""
        if cur != text:
            print("item_drop_models.inc is stale; rerun tools/gen_item_drop_models.py")
            return 1
        print("item_drop_models.inc is current")
        return 0
    with open(OUT, "wb") as fh:
        fh.write(text.encode("utf-8"))
    print("wrote", OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
