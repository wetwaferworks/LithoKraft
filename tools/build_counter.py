#!/usr/bin/env python3
# 2026-10-18 (JD): the rolling build counter.
#
# Eight wheels, each holding 0..63 (base 64, so 64^8 = 2^48 builds). EVERY build
# increments the rightmost wheel by 1; a wheel that would reach 64 rolls to 0 and
# carries +1 to the wheel on its left, cascading as needed. The display is plain
# decimal, human-readable: the eight wheels printed as decimal numbers separated
# by dots, e.g. 0.0.0.0.0.0.0.1. No hex, no letters.
#
# State lives in the tracked file <tree>/BUILD_COUNTER.txt so it survives build-dir
# wipes. Each roll also appends "timestamp value total" to the append-only ledger
# <tree>/BUILD_COUNTER.log, and regenerates the C++ header the game binary prints
# at startup. Display/log only: the counter never feeds the determinism hash.
#
# Usage (from CMake): build_counter.py --state F --header F --log F
# A missing state file is recreated at the seed 0.0.0.0.0.0.0.0, then incremented.
# The state write is atomic (temp file + rename) so a killed build cannot corrupt it.
import argparse
import os
import sys
import tempfile
from datetime import datetime, timezone

WHEELS = 8
BASE = 64
SEED = [0] * WHEELS

# Wheel-ink palette (JD, 2026-10-18): wherever the counter is displayed,
# even-index wheels ink in muted lavender, odd-index wheels in warm gray, and
# any wheel that WRAPPED on the build that produced the value inks in brand
# orange for that display. The orange is the SelectOR bus orange — the game's
# circuit-glow orange (game/LithoKraft/src/content/model/agent_models.h:
# kGlowOrange {255, 140, 26}, "Selector orange"). Wheel index 0 is the
# leftmost wheel, matching kJdBuildCounterWheels[0..7] in the header.
# These constants are the single source of truth: this script inks its own
# build-console line from them, and header_text() emits the per-wheel ink
# into the generated header for the game's startup line.
INK_EVEN = (0xA7, 0x9B, 0xC4)  # muted lavender  #A79BC4
INK_ODD = (0xA8, 0x9E, 0x92)   # warm gray       #A89E92
INK_WRAP = (0xFF, 0x8C, 0x1A)  # brand orange    #FF8C1A (SelectOR bus orange)


def wheel_ink(i, wrapped):
    if wrapped[i]:
        return INK_WRAP
    return INK_EVEN if i % 2 == 0 else INK_ODD


def inked_display(wheels, wrapped):
    """The display string with one ANSI truecolor span per wheel (dots plain)."""
    return ".".join(
        "\x1b[38;2;%d;%d;%dm%d\x1b[0m" % (*wheel_ink(i, wrapped), wheels[i])
        for i in range(WHEELS)
    )


def parse_state(text):
    # 2026-10-23 (JD/Cortana fix run 2): tolerate an optional "Litho Engine " label.
    text = text.strip()
    if text.startswith("Litho Engine "):
        text = text[len("Litho Engine "):]
    parts = text.strip().split(".")
    if len(parts) != WHEELS:
        raise ValueError(f"expected {WHEELS} dot-separated wheels, got {len(parts)}")
    wheels = []
    for p in parts:
        w = int(p)
        if not 0 <= w < BASE:
            raise ValueError(f"wheel value {w} out of range 0..{BASE - 1}")
        wheels.append(w)
    return wheels


def increment(wheels):
    """+1 with base-64 carry. Returns (new_wheels, wrapped): wrapped[i] is
    True for each wheel that rolled past 63 on this increment."""
    w = list(wheels)
    wrapped = [False] * WHEELS
    for i in range(WHEELS - 1, -1, -1):
        w[i] += 1
        if w[i] < BASE:
            return w, wrapped
        w[i] = 0
        wrapped[i] = True
    return w, wrapped  # 63.63.63.63.63.63.63.63 wraps to all zeros, all wrapped


def total_count(wheels):
    t = 0
    for w in wheels:
        t = t * BASE + w
    return t


def display(wheels):
    return ".".join(str(w) for w in wheels)


def atomic_write(path, text):
    d = os.path.dirname(os.path.abspath(path))
    fd, tmp = tempfile.mkstemp(dir=d, prefix=".build_counter-", text=True)
    try:
        with os.fdopen(fd, "w") as f:
            f.write(text)
        os.replace(tmp, path)
    except BaseException:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise


def header_text(wheels, wrapped):
    disp = display(wheels)
    tot = total_count(wheels)
    inks = ", ".join("0x%02X%02X%02Xu" % wheel_ink(i, wrapped) for i in range(WHEELS))
    return (
        "// Generated by tools/build_counter.py on every build. Do not edit.\n"
        "// JD rolling build counter: 8 wheels, base 64 (64^8 = 2^48 builds).\n"
        "#pragma once\n"
        "#include <cstdint>\n"
        "\n"
        f'#define JD_BUILD_COUNTER_DISPLAY "{disp}"\n'
        f"#define JD_BUILD_COUNTER_TOTAL {tot}ULL\n"
        f"inline constexpr int kJdBuildCounterWheels[8] = "
        f"{{{', '.join(str(w) for w in wheels)}}};\n"
        "// Wheel ink for this build's displays (JD 2026-10-18): even wheels muted\n"
        "// lavender #A79BC4, odd wheels warm gray #A89E92, wheels that wrapped on\n"
        "// this build brand orange #FF8C1A (SelectOR bus orange). Index 0 = leftmost.\n"
        f"inline constexpr std::uint32_t kJdBuildCounterWheelInk[8] = {{{inks}}};\n"
        f'inline constexpr const char* kJdBuildCounterDisplay = "{disp}";\n'
        f"inline constexpr std::uint64_t kJdBuildCounterTotal = {tot}ULL;\n"
    )


def main():
    ap = argparse.ArgumentParser(description="Roll JD's build counter by one build.")
    ap.add_argument("--state", required=True, help="BUILD_COUNTER.txt path")
    ap.add_argument("--header", required=True, help="generated build_counter.h path")
    ap.add_argument("--log", required=True, help="BUILD_COUNTER.log ledger path")
    # 2026-10-23 (JD, fix run 2): builds no longer roll the engine counter. With
    # --no-bump the state is only READ (never written) and the header is regenerated.
    ap.add_argument("--no-bump", action="store_true", help="read-only: do not roll or write state/log")
    args = ap.parse_args()

    if os.path.exists(args.state):
        with open(args.state) as f:
            wheels = parse_state(f.read())
    else:
        wheels = list(SEED)
    if args.no_bump:
        wrapped = [False] * WHEELS
    else:
        wheels, wrapped = increment(wheels)
        atomic_write(args.state, display(wheels) + "\n")

    header_dir = os.path.dirname(os.path.abspath(args.header))
    os.makedirs(header_dir, exist_ok=True)
    atomic_write(args.header, header_text(wheels, wrapped))

    if not args.no_bump:
        ts = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
        with open(args.log, "a") as f:
            f.write(f"{ts} {display(wheels)} {total_count(wheels)}\n")

    # Build-console display surface: inked on a real terminal, byte-identical
    # plain text when captured (build logs, CI) so log scrapers see no change.
    if sys.stdout.isatty():
        print(f"JD build counter: {inked_display(wheels, wrapped)}")
    else:
        print(f"JD build counter: {display(wheels)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
